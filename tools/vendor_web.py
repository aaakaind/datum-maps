"""Vendor the web app's third-party files into the Android app.

The web app loads MapLibre GL JS and d3 from cdnjs and its typefaces from Google
Fonts. The Android app serves local copies of those files instead, so the app
opens without a network connection and sends nothing to a CDN or to Google.

  python3 tools/vendor_web.py android/app/src/main/assets/vendor

Writes:
  <out>/maplibre-gl-<v>.js, <out>/d3-<v>.min.js   checked against cdnjs's SRI hashes
  <out>/fonts/*.woff2, <out>/fonts/fonts.css       Google Fonts CSS rewritten to local files
  <out>/vendor.json                                 original URL -> asset path, read by the app
  <out>/LICENSES.md                                 licences of everything vendored
"""
import base64
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ORIGIN = "https://appassets.androidplatform.net"
UA_BROWSER = ("Mozilla/5.0 (Linux; Android 16; SM-F956W) AppleWebKit/537.36 "
              "(KHTML, like Gecko) Chrome/141.0.0.0 Mobile Safari/537.36")
UA_TOOL = "DATUM-vendor/0.2 (AKA IND; github.com/aaakaind/datum-maps)"
LICENCES = [
    ("MapLibre GL JS", "BSD-3-Clause", "https://raw.githubusercontent.com/maplibre/maplibre-gl-js/main/LICENSE.txt"),
    ("d3", "ISC", "https://raw.githubusercontent.com/d3/d3/main/LICENSE"),
    ("IBM Plex Sans, IBM Plex Mono", "SIL Open Font License 1.1", "https://raw.githubusercontent.com/IBM/plex/master/LICENSE.txt"),
    ("Jost", "SIL Open Font License 1.1", "https://raw.githubusercontent.com/google/fonts/main/ofl/jost/OFL.txt"),
]


def get(url, ua=UA_TOOL):
    req = urllib.request.Request(url, headers={"User-Agent": ua})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def sri_ok(data, sri):
    algo, _, want = sri.partition("-")
    return base64.b64encode(hashlib.new(algo, data).digest()).decode() == want


def main(out):
    out = Path(out)
    (out / "fonts").mkdir(parents=True, exist_ok=True)
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    mapping = {}

    # Scripts from cdnjs, verified against the SRI hash cdnjs publishes.
    for url in re.findall(r'<script src="(https://cdnjs\.cloudflare\.com/ajax/libs/[^"]+)"', html):
        lib, ver, fname = url.split("/ajax/libs/")[1].split("/", 2)
        meta = json.loads(get(f"https://api.cdnjs.com/libraries/{lib}/{ver}?fields=sri"))
        data = get(url)
        sri = meta["sri"].get(fname)
        if not sri or not sri_ok(data, sri):
            raise SystemExit(f"SRI check failed for {url}")
        stem, ext = fname.split(".", 1)
        local = f"{stem}-{ver}.{ext}"
        (out / local).write_bytes(data)
        mapping[url] = f"vendor/{local}"
        print(f"{url} -> {local} ({len(data) // 1024} KB, {sri.split('-')[0]} ok)")

    # Google Fonts: fetch the CSS as a current Android Chrome would, then point every
    # woff2 at a local copy.
    css_url = re.search(r'<link rel="stylesheet" href="(https://fonts\.googleapis\.com/css2\?[^"]+)"', html).group(1)
    css_url = css_url.replace("&amp;", "&")
    css = get(css_url, UA_BROWSER).decode()
    fonts = 0
    for furl in sorted(set(re.findall(r"url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)", css))):
        parts = furl.split("/s/")[1].split("/")
        local = f"{parts[0]}-{parts[1]}-{parts[-1]}"
        (out / "fonts" / local).write_bytes(get(furl, UA_BROWSER))
        css = css.replace(furl, f"{ORIGIN}/vendor/fonts/{local}")
        fonts += 1
    (out / "fonts" / "fonts.css").write_text(css, encoding="utf-8")
    mapping[css_url] = "vendor/fonts/fonts.css"
    print(f"{css_url[:70]}... -> fonts/fonts.css ({fonts} font files)")

    (out / "vendor.json").write_text(json.dumps(mapping, indent=1) + "\n", encoding="utf-8")

    intro = ("Generated by tools/vendor_web.py. Each file below is an unmodified copy of a "
             "file the web app loads from a CDN, except fonts.css, whose font URLs are "
             "rewritten to the local copies.\n")
    parts = ["# Third-party files vendored into the DATUM Android app\n", intro]
    for name, spdx, url in LICENCES:
        parts.append(f"\n## {name} ({spdx})\n\nSource: {url}\n\n```\n{get(url).decode().strip()}\n```\n")
    (out / "LICENSES.md").write_text("".join(parts), encoding="utf-8")
    print("vendor.json and LICENSES.md written")


if __name__ == "__main__":
    main(sys.argv[1])
